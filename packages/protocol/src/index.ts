// Data shapes and messages shared by gasho-daemon, gasho-hub and gasho-web.
// This package contains types only, so every import of it must be `import type`.

/**
 * Status reported by `claude agents --json`. Claude Code reports "busy" also after Claude's turn has ended while work
 * it started runs on in the background; gasho-daemon reports "idle" when only shells and monitors run on then (see
 * SessionInfo.background).
 */
export type SessionStatus = "busy" | "waiting" | "idle" | "unknown";

/** What a background task is: a shell command, a monitor (a command whose output wakes Claude), a subagent, a workflow. */
export type BackgroundTaskKind = "shell" | "monitor" | "agent" | "workflow";

/**
 * Work that Claude Code runs in the background for a session (a tool called with `run_in_background`, a monitor, a
 * subagent, a workflow). It runs on after Claude's turn has ended, until it finishes or is stopped.
 */
export interface BackgroundTask {
  /** Claude Code's id for it (a shell's task id, a subagent's agentId). */
  id: string;
  kind: BackgroundTaskKind;
  /** What it is for: the description Claude gave it, or else what it runs. */
  title: string;
  /** Shells and monitors: the command. */
  command?: string;
  /** When Claude started it (ms). */
  startedAt?: number;
}

/**
 * How the session is reachable from the official apps.
 * - server: spawned by `claude remote-control` (server mode)
 * - interactive: an interactive session with Remote Control enabled
 * - none: a local session without Remote Control
 */
export type RcMode = "server" | "interactive" | "none";

export interface GitHubRepo {
  owner: string;
  name: string;
  url: string;
}

export interface PrLink {
  number: number;
  url: string;
  repository: string;
}

/** A Git repository inside a session's folder, for a folder that is not itself in a repository. */
export interface SessionRepo {
  /** Path from the session's folder, such as "app" or "org/app". */
  path: string;
  branch?: string;
  github?: GitHubRepo;
}

/** The git worktree a session's folder is in. Older gasho-daemons do not tell it. */
export interface SessionWorktree {
  /** The worktree's top folder. */
  path: string;
  /** The repository: the folder of its main worktree (of the repository itself, when bare). Its worktrees share it. */
  repo: string;
  /** Absent when HEAD is detached. */
  branch?: string;
}

/** A repository registered with a working server (repo.register): the sidebar lists its worktrees, also without sessions. */
export interface RegisteredRepo {
  /** Its folder, as SessionWorktree.repo names it. */
  path: string;
  github?: GitHubRepo;
  /** Its worktrees whose folder is there, as `git worktree list` gives them (the main one first). */
  worktrees: RepoWorktree[];
  /** Why its worktrees could not be read (its folder is gone, or is no longer a repository). */
  error?: string;
}

export interface RepoWorktree {
  /** Its top folder, as SessionWorktree.path names it. */
  path: string;
  /** Absent when HEAD is detached. */
  branch?: string;
}

/**
 * A repository that MachineInfo.folders are in (or, for a folder outside any repository, whose worktrees are directly
 * inside it): one that repo.register would register for one of those folders.
 */
export interface FolderRepo {
  /** Its folder, as SessionWorktree.repo names it. */
  path: string;
  /** How many worktrees `git worktree list` gives it (the main one too), as RegisteredRepo.worktrees counts them. */
  worktreeCount: number;
}

export interface SessionInfo {
  /** Local session id (UUID); for Codex, the id of its thread. */
  sessionId: string;
  /** The agent that runs the session. Absent means Claude Code. */
  agent?: AgentKind;
  pid?: number;
  cwd: string;
  name?: string;
  /** Title generated by Claude Code (`ai-title` in the transcript). */
  title?: string;
  kind?: string;
  status: SessionStatus;
  waitingFor?: string;
  startedAt?: number;
  /** `session_…` id used in https://claude.ai/code/<id>. */
  bridgeSessionId?: string;
  rcMode: RcMode;
  gitBranch?: string;
  github?: GitHubRepo;
  prLinks: PrLink[];
  costUSD?: number;
  lastActivityAt?: number;
  /** Started by Gasho (in a terminal of gasho-daemon's), so Gasho can send input to it. */
  managed?: boolean;
  /** Inputs waiting until the session is idle. */
  pendingInputs?: number;
  /**
   * Sessions started from Gasho: the ids the session had before, oldest first. /clear (and /resume) make Claude Code go
   * on in the same process under a new id; a page still open on an earlier id goes to this session.
   */
  previousSessionIds?: string[];
  /** Repositories inside the folder, when the folder is not in a repository but holds some (a workspace of repos). */
  repos?: SessionRepo[];
  /** Absent when the folder is not in a repository. */
  worktree?: SessionWorktree;
  /** The model the session uses, as Claude Code names it ("Opus 5.5"); from the transcript. */
  model?: string;
  /** Sessions started from Gasho: the effort level and ultracode as Claude Code shows them above the prompt. */
  effort?: EffortLevel;
  ultracode?: boolean;
  /** Sessions started from Gasho: the tokens used so far, by the session's replies and its subagents'. */
  tokens?: TokenUsage;
  /** …and per hour over the last 48 hours, oldest first: [start of the hour (ms), use]. Hours without use are left out. */
  tokenHours?: [number, TokenUsage][];
  /**
   * Sessions started from Gasho by a gasho-daemon of plugin API 1.4 or later: the context window, as Claude Code's
   * status line last reported it. Absent until the session's first reply.
   */
  context?: ContextWindow;
  /**
   * …and the Claude.ai plan's usage limits, as of the session's latest reply. Absent until then, and when the session
   * does not use a Claude.ai plan (an API key).
   */
  limits?: PlanLimits;
  /**
   * Permission requests waiting for an answer, oldest first (Claude Code's PermissionRequest hook). They can be
   * answered from Gasho (`permission.answer`), or in the terminal or the official apps, which removes them here.
   */
  permissionRequests?: PermissionRequestInfo[];
  /**
   * Work Claude Code runs in the background for the session, oldest first, as its transcript records it; absent when
   * none runs, and from a gasho-daemon that does not read it. Sessions started from Gasho can stop it
   * (`session.stopTask`).
   */
  background?: BackgroundTask[];
  /**
   * Sessions started from Gasho that nobody used for a while: "hibernated" while their Claude Code does not run (their
   * conversation can still be read, and `status` stays "idle"), "resuming" while it starts again. An input sent to the
   * session brings it back and is typed then. Absent while the session runs.
   */
  hibernation?: "hibernated" | "resuming";
  /** Why a hibernated session could not be brought back; `session.wake` tries again. Inputs sent to it are kept. */
  resumeError?: string;
  /**
   * Sessions started with `gasho-daemon session launch` from another session's Claude Code (a session's Agent sets
   * up a worktree and starts a session in it; see the skill gasho:launch-gasho-session): that session. Absent for
   * the rest, and from a gasho-daemon before it was added.
   */
  launchedBy?: SessionParent;
}

/**
 * The session whose Claude Code started a session with `gasho-daemon session launch`, as it was then. A parent's id
 * changes with /clear: `sessionId` is its id now while gasho-daemon keeps the parent (one of the sessions it started),
 * and the id it had then otherwise (the parent may be gone). `cwd` stays: the worktree of the parent can outlive it.
 */
export interface SessionParent {
  sessionId: string;
  /** The parent's folder when it started the session. */
  cwd: string;
}

/** A permission Claude Code asks for before using a tool. */
export interface PermissionRequestInfo {
  /** Given by gasho-daemon; answers name it. */
  id: string;
  toolName: string;
  /** The tool's input as pretty JSON, clipped. */
  input: string;
  /** Its most telling field (the command, the file, …). */
  summary?: string;
  at: number;
  /**
   * What "allow from now on" would allow, in Claude Code's notation ("Bash(npm test:*)"), when Claude Code suggests
   * a permanent rule for this request; absent when it does not, and "always" cannot be answered.
   */
  always?: string;
  /**
   * AskUserQuestion: the questions Claude asks the person. "allow" answers them with `answers`; without answers,
   * Claude Code would keep its own dialog open. Absent when gasho-daemon cannot pass answers on (before this field).
   */
  questions?: AskedQuestion[];
  /**
   * ExitPlanMode: the plan Claude asks to go ahead with (Markdown, clipped). "allow" approves it (and the session goes
   * on in the `mode` given); "deny" with a `message` sends it back for Claude to plan again. Absent when gasho-daemon
   * cannot approve a plan (before this field).
   */
  plan?: string;
  /**
   * A question that gasho-daemon holds no hook for (it restarted while the question was open, the hook timed out, or
   * it was spent): shown from the transcript, for a session started from Gasho. Answering it closes Claude Code's
   * dialog (Claude is told the person declined it) and sends the answers as the next message.
   */
  answerAsMessage?: boolean;
}

/** One question of an AskUserQuestion. */
export interface AskedQuestion {
  question: string;
  /** A short label for it ("Auth method"). */
  header?: string;
  options: AskedOption[];
  /** More than one option can be chosen. */
  multiSelect?: boolean;
}

export interface AskedOption {
  label: string;
  description?: string;
  /** Something to look at when the option is chosen (a mockup, a code snippet), shown in a monospace box. */
  preview?: string;
}

/**
 * The answer to one question of an AskUserQuestion: the options chosen (indexes into its `options`; at most one when
 * it is not multiSelect) and what the person wrote instead of an option, or besides them.
 */
export interface QuestionAnswer {
  picked: number[];
  text?: string;
}

/** The permission mode a session goes on in once its plan is approved: auto mode, or asking before each edit. */
export type PlanMode = "auto" | "default";

/** allow: this once. always: this time and from now on, as Claude Code suggests. deny: Claude stops and waits. */
export type PermissionDecision = "allow" | "always" | "deny";

/** A session's context window, from Claude Code's status line (its `context_window`). */
export interface ContextWindow {
  /** Input tokens in the context now: the latest reply's input, cache writes and cache reads. */
  used: number;
  /** The size of the model's context window (200000, 1000000). */
  size: number;
  /** The share used, 0-100, as Claude Code works it out (a whole number). */
  percent: number;
  /** When Claude Code reported it (ms since the epoch, the working server's clock). */
  at: number;
}

/** A usage limit of the Claude.ai plan: the share of it used, and when it starts again. */
export interface UsageWindow {
  /** 0-100 */
  percent: number;
  /** ms since the epoch */
  resetsAt: number;
}

/**
 * The Claude.ai plan's usage limits, from Claude Code's status line (its `rate_limits`, which Claude Code reads from
 * the headers of the API's replies). They are the account's, the same for every session that uses its login.
 */
export interface PlanLimits {
  /** The 5-hour limit; some plans have none. */
  fiveHour?: UsageWindow;
  /** The weekly limit, all models together. */
  sevenDay?: UsageWindow;
  /** When Claude Code reported them (ms since the epoch, the working server's clock). */
  at: number;
}

/**
 * A usage limit as Claude Code's get_usage reads it: the share used (0-100), and when it starts again (ms since the
 * epoch). Claude.ai gives some without a time (a window nothing has been used in yet).
 */
export interface PlanUsageWindow {
  percent: number;
  resetsAt?: number;
}

/**
 * The Claude.ai plan's usage limits, as gasho-daemon read them with Claude Code's get_usage (as its /usage does). Unlike
 * PlanLimits, they hold the weekly limits of single models (Fable, …). They are the account's: the same for every
 * session that uses the working server's Claude Code login.
 */
export interface PlanUsage {
  /** When they were read (ms since the epoch, the working server's clock). */
  at: number;
  /**
   * false: get_usage cannot read them with the working server's Claude Code login: it does not use a Claude.ai plan
   * (an API key and the like), or its token may not read the account's usage (claude setup-token).
   */
  available: boolean;
  /** The 5-hour limit; some plans have none. */
  fiveHour?: PlanUsageWindow;
  /** The weekly limit, all models together. */
  sevenDay?: PlanUsageWindow;
  /** The weekly limit of the Sonnet models ("Current week (Sonnet only)" of /usage), on the plans /usage shows it for. */
  sevenDaySonnet?: PlanUsageWindow;
  /** The weekly limits of single models, named as Claude.ai names them. */
  models: (PlanUsageWindow & { name: string })[];
}

/** What the Gasho server knows of a working server's plan usage (usage.get): kept in memory, also while it is offline. */
export interface MachineUsage {
  /** The latest limits read. */
  usage?: PlanUsage;
  /** Why the latest read failed, when it did (after `usage`, if any). */
  error?: string;
  /** A read is under way. */
  reading?: boolean;
}

/** Tokens as Claude Code records them for each reply. */
export interface TokenUsage {
  input: number;
  output: number;
  /** Written to the prompt cache. */
  cacheWrite: number;
  /** Read from the prompt cache (the conversation so far, read again at every turn). */
  cacheRead: number;
}

/**
 * What a file Claude sent to the person is shown as, by the extension of its name: an image or a video in the
 * conversation, any other file by its name only.
 */
export type SentFileKind = "image" | "video" | "file";

/** A file Claude sent to the person (Claude Code's SendUserFile tool). */
export interface SentFile {
  /**
   * Where it is on the working server: an absolute path (one the call gave from the session's folder is made absolute).
   * A path that could not be made absolute stays as the call gave it, as a "file".
   */
  path: string;
  kind: SentFileKind;
}

/** The files Claude sent to the person with a call of Claude Code's SendUserFile tool. */
export interface SentFiles {
  files: SentFile[];
  caption?: string;
  /** Claude asked for them to be offered as files rather than shown (display "attach"). */
  attach?: boolean;
}

export type TranscriptBlock =
  | { type: "text"; text: string }
  /**
   * `sent`: the call sent files to the person (SendUserFile), which the screen shows instead of the call's fold (an
   * older screen shows the fold, as for any call; an older gasho-daemon does not say). The images and videos among them
   * are read from the working server when they are shown (media.get), so they show what the files hold then.
   */
  | { type: "tool_use"; id?: string; name: string; input: string; summary?: string; sent?: SentFiles }
  | { type: "tool_result"; toolUseId?: string; content: string; isError: boolean }
  | { type: "image" };

/** Part of an image or a video Claude sent to the person in a session (media.get). */
export interface MediaPart {
  /** Its type, by the extension of its name ("image/png", "video/mp4"). */
  mime: string;
  /** The whole file: its size in bytes, and when it was last changed (ms since the epoch). */
  size: number;
  mtime: number;
  /** Where the part starts in the file, and its bytes, base64-encoded: fewer than asked for at the end of the file. */
  offset: number;
  data: string;
}

export interface TranscriptEntry {
  uuid: string;
  ts?: string;
  role: "user" | "assistant" | "system";
  blocks: TranscriptBlock[];
  isSidechain?: boolean;
  /** True when the entry is Claude Code's "[Request interrupted by user]" marker. */
  interrupted?: boolean;
  /**
   * Set on the two system entries of a compaction, when Claude Code summarized the conversation to free its context:
   * "mark" is where it did ("Conversation compacted"), "summary" is the summary the conversation goes on from (Claude
   * Code records it as a user message, which the user did not write). The summary follows its mark.
   */
  compaction?: "mark" | "summary";
}

