/** A file sent with an input, base64-encoded. The Gasho server allows 5 files and 10 MB in all per input. */
export interface InputFile {
  name: string;
  data: string;
}

/** Commands a browser can send to a working server, relayed by the Gasho server. */
export type SessionCommand =
  /**
   * `name`: without one, the session is "<folder>-gasho" until its first message, and is then named after it, with the
   * title Claude Code gives the conversation (gasho-daemon 0.10.0 and later; older ones keep "<folder>-gasho").
   * `trust`: when Claude Code asks whether to trust the folder (one it does not trust yet), answer "Yes, I trust this
   * folder" (gasho-daemon 0.10.0 and later). Without it, the launch stops at the question and its result says so
   * (`needsTrust`), so that the person decides.
   */
  /**
   * `agent`: the agent to start; Claude Code when absent. `trust` is about Claude Code's question only. `effort`: Claude
   * Code starts with it (`--effort`, for this session only); the Gasho server gives its default effort level
   * (ServerInfo.defaultEffort) to a launch of Claude Code without one. A model that does not have it starts with one it
   * has, or none. `model`: likewise (`--model`, ServerInfo.defaultModel); "default" passes nothing. A launch from the
   * control socket gets them from launch.defaults.
   */
  | { type: "session.launch"; cwd: string; name?: string; trust?: boolean; agent?: AgentKind; effort?: EffortLevel; model?: SessionModel }
  /** Makes the folder `name` inside the folder `parent` (gasho-daemon 0.10.0 and later). */
  | { type: "folder.create"; parent: string; name: string }
  /**
   * Clones a GitHub repository into the folder `parent` with the working server's GitHub CLI (`gh repo clone`, with its
   * login), as the folder `name` (by default, the repository's name). `repo`: "owner/name", "name" (a repository of the
   * account gh is logged in with), or its URL (gasho-daemon 0.10.0 and later).
   */
  | { type: "repo.clone"; parent: string; repo: string; name?: string }
  /**
   * Registers the repository that the folder `path` is in, so that the sidebar lists its worktrees. A folder in one of
   * its worktrees registers the repository's own folder (SessionWorktree.repo), which the result gives (`path`). So does
   * a folder outside any repository that has worktrees of only that repository directly inside it.
   */
  | { type: "repo.register"; path: string }
  /** Takes a registered repository (its folder, as MachineInfo.repos names it) off the list. */
  | { type: "repo.unregister"; path: string }
  /**
   * `model`, `effort`, `ultracode`: switch the session (for this session only) before the text is sent.
   * `files`: saved on the working server and mentioned at the end of the text (`@path`), so Claude reads them.
   */
  | {
      type: "session.input";
      sessionId: string;
      text: string;
      model?: SessionModel;
      effort?: EffortLevel;
      ultracode?: boolean;
      files?: InputFile[];
      /** Sent by a plugin (its id), for the operations log. */
      via?: string;
    }
  /**
   * Stops Claude's turn (Esc). When the turn has ended and Claude waits only for its subagents and workflows in the
   * background, stops those instead (Claude Code's "stop background agents").
   */
  | { type: "session.interrupt"; sessionId: string }
  /**
   * Stops work running in the background in a session started from Gasho: the task `taskId` (one of its `background`),
   * or without it, all of them. Done in Claude Code's list of background tasks, as when stopped there by hand.
   */
  | { type: "session.stopTask"; sessionId: string; taskId?: string }
  /**
   * Renames a session started from Gasho: in Gasho at once, and in Claude Code with `/rename` (also the name in the
   * official apps), typed like an input once the session is idle.
   */
  | { type: "session.rename"; sessionId: string; name: string }
  /**
   * Starts a copy of a session started from Gasho, with its conversation so far, in the same folder
   * (`claude --resume <id> --fork-session`). The session itself goes on as it was.
   */
  | { type: "session.fork"; sessionId: string; name?: string }
  /**
   * Ends a session started from Gasho (its Claude Code, then its terminal) and removes it from Gasho. Its
   * conversation stays on the working server: `claude --resume` lists it. `via`: sent by a plugin (its id), for the
   * operations log.
   */
  | { type: "session.remove"; sessionId: string; via?: string }
  /**
   * The conversations Claude Code keeps for the folder `cwd` (with `subfolders`, also for the folders inside it) that
   * no Claude Code has open now, the latest first (`history`). Only reads; the operations log does not record it.
   */
  | { type: "session.history"; cwd: string; subfolders?: boolean }
  /**
   * The skills and custom commands that the session's Claude Code reads (`skills`): the person's own (~/.claude), its
   * folder's (.claude, up to the top of its repository), its plugins' and those synced from claude.ai. Claude Code's
   * built-in commands are not among them. Only reads; the operations log does not record it.
   */
  | { type: "session.skills"; sessionId: string }
  /**
   * Opens a conversation of session.history again in its folder, as a session started from Gasho
   * (`claude --remote-control=<name> --resume <id>`). Its name is the conversation's.
   */
  | { type: "session.resume"; sessionId: string }
  /** Brings a hibernated session back (`SessionInfo.hibernation`) without sending it anything. */
  | { type: "session.wake"; sessionId: string }
  /**
   * Ends the Claude Codes that have these sessions open, started outside Gasho (in Orca, a terminal), as on a shutdown
   * (SIGTERM), so that their conversations can be opened again from Gasho (session.history, session.resume). Their
   * terminals stay open. One that does not end is left running.
   */
  | { type: "session.end"; sessionIds: string[] }
  /**
   * Answers one of a session's `permissionRequests`. A request with `questions` takes "allow" with `answers` (one per
   * question, in order). A request with a `plan`: "allow" approves it and goes on in `mode` (when given). "deny" with
   * a `message`: Claude is told it and goes on from there (a plan: plans again), instead of stopping.
   */
  | {
      type: "permission.answer";
      sessionId: string;
      permissionId: string;
      decision: PermissionDecision;
      answers?: QuestionAnswer[];
      mode?: PlanMode;
      message?: string;
    }
  /**
   * Writes a text file inside the session's folder (`path` as in file.get), as UTF-8, up to 1 MB (gasho-daemon 0.11.0
   * and later). `baseHash`: the file's hash when it was read; if the file is no longer that, nothing is written and
   * the result says so (`conflict`). Without it, the file is overwritten. `create`: makes a new file instead, in a
   * folder that is there; nothing that is already there is overwritten.
   */
  | { type: "file.write"; sessionId: string; path: string; content: string; baseHash?: string; create?: boolean }
  /**
   * Updates gasho-daemon to `version`, or takes it back to an older one, when its `update.canUpdate` (gasho-daemon
   * says so only from the version that brought updates from Gasho on). gasho-daemon installs that version beside the running one, checks that it starts, waits for the
   * inputs it still has to send, switches to it and ends, for its service to start the new version. The result comes
   * as soon as the update has begun; `update.progress` follows it, and the new version's connection ends it (or
   * `update.failed`, with nothing changed).
   */
  | { type: "daemon.update"; version: string }
  /**
   * Removes a worktree of a repository (`git worktree remove`), with the sessions in it (canRemoveWorktree). `path`: its
   * top folder, one that `git worktree list` lists and not the repository's main worktree. Sessions whose folder is in
   * it end first: those started from Gasho as with session.remove, the others as with session.end; if one does not
   * end, nothing is removed. A worktree with uncommitted changes, or with commits that no remote has, is not removed
   * unless `force`: the result says how many (`changes`). `pushed`: commits counted as pushed (such as the head of a
   * merged pull request, whose branch on GitHub may be gone). `branch`: the branch the worktree has checked out, also
   * deleted (`git branch -D`) once the worktree is gone. `via`: sent by a plugin (its id), for the operations log.
   */
  | { type: "worktree.remove"; path: string; branch?: string; force?: boolean; pushed?: string[]; via?: string };

/** What keeps a worktree from being removed without `force` (worktree.remove). */
export interface WorktreeChanges {
  /** Uncommitted changes: files changed, staged or untracked (`git status --porcelain`). */
  uncommitted: number;
  /** Commits of its HEAD that no remote branch has, nor any of the commits given as `pushed`. */
  unpushed: number;
}

export interface CommandResult {
  ok: boolean;
  error?: string;
  /**
   * session.launch, session.fork, session.resume: the new session. session.input: whether the input waits for the session to become
   * idle; session.rename: whether `/rename` does.
   */
  sessionId?: string;
  queued?: boolean;
  /** Sent, but something asked for did not happen (e.g. the model could not be switched). */
  warning?: string;
  /** session.input: what was asked to switch but was not switched (the session keeps what it had). */
  unapplied?: SwitchField[];
  /** folder.create, repo.clone: the folder that was made (an absolute path). repo.register: the repository's folder. */
  path?: string;
  /**
   * session.launch without `trust`: Claude Code asked whether to trust the folder, so nothing was started.
   * `trustWarnings`: what Claude Code pointed out about the folder's own settings while asking (as it wrote it, in
   * English), such as permissions the folder allows in advance.
   */
  needsTrust?: boolean;
  trustWarnings?: string[];
  /** file.write: the file as written. */
  written?: FileStamp;
  /** file.write with `baseHash`: the file changed after it was read (by Claude, or anyone else), so it was not written. */
  conflict?: boolean;
  /** session.history: the conversations, the latest first. */
  history?: PastConversation[];
  /**
   * session.end: the sessions whose Claude Code has ended (or had ended already). worktree.remove: the sessions it
   * ended (also when it then failed).
   */
  ended?: string[];
  /** worktree.remove without `force`: not removed because of these. */
  changes?: WorktreeChanges;
  /** session.skills: what can be typed after "/", by name. */
  skills?: SkillInfo[];
}

/** A skill or custom command that a session's Claude Code takes after "/". */
export interface SkillInfo {
  /** What follows the "/" ("impl-review", "nakamaba:nakamaba", "anthropic-skills:pdf"). */
  name: string;
  /** The start of its description (or of its text, when it has none), on one line. */
  description?: string;
}

/** A conversation Claude Code keeps on a working server, which no Claude Code has open now. */
export interface PastConversation {
  sessionId: string;
  /** Its name (/rename), or the title Claude Code gave it, or the start of its first message. */
  title?: string;
  /** The folder it ran in. */
  cwd: string;
  /** When its transcript was last written (ms since the epoch). */
  lastActivityAt: number;
}
